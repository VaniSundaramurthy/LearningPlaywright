//Logical Operators
//Logical operators are used to combine multiple boolean expressions and return a boolean value based on the logical relationship between them. Here are the common logical operators in JavaScript:

// 1. Logical AND (&&)
// Returns true if both operands are true, otherwise returns false.
console.log(true && true);   // true
console.log(true && false);  // false
console.log(false && false); // false

// 2. Logical OR (||)
// Returns true if at least one operand is true, otherwise returns false.
console.log(true || true);   // true
console.log(true || false);  // true
console.log(false || false); // false

// 3. Logical NOT (!)
// Returns the opposite boolean value of the operand.
console.log(!true);  // false
console.log(!false); // true