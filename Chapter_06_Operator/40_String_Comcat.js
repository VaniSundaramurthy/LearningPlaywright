//String Contanenation
//String concatenation is the process of combining two or more strings into one. In JavaScript, you can concatenate strings using the + operator or the += operator.
//realtime example of string concatenation
let firstName = "John";
let lastName = "Doe";
let fullName = firstName + " " + lastName;  

//Different examples of string concatenation

let greeting = "Hello, " + fullName + "!"; // Using + operator
console.log(greeting); // Output: Hello, John Doe!

let message = "Welcome, ";
message += fullName;

console.log(message); // Output: Welcome, John Doe!

