//Switch with No Break in JavaScript
let day = 3;

switch (day) {
    case 1:
        console.log("Monday");
    case 2:
        console.log("Tuesday");
    case 3:
        console.log("Wednesday");

    case 4:
        console.log("Thursday");
    case 5:
        console.log("Friday");
    case 6:
        console.log("Saturday");
    case 7:
        console.log("Sunday");
    default:
        console.log("Invalid day");
}

//Real Time example of switch with no break in JavaScript
let grade = 'B';

switch (grade) {

    case 'A':
        console.log("Excellent");
    case 'B':
        console.log("Good");
    case 'C':
        console.log("Average");
    case 'D':
        console.log("Below Average");
    case 'F':
        console.log("Fail");
    default:
        console.log("Invalid grade");
}


